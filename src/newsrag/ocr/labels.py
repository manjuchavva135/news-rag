"""labels.yaml: every Surya layout label mapped to exactly one group (FR-6).

The groups are `newsrag.config.LABEL_GROUPS`. A label missing from the file maps to `other`.
`newsrag ocr labels` (re)writes the file from Surya's label list, keeping mappings that are
already there and suggesting a group for new labels; a person then reviews it.
"""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path

import yaml

from newsrag import config
from newsrag.config import LABEL_GROUPS, read_label_groups

OTHER = "other"

# Groups whose regions indic-ocr reads, and the block type they are sent with (FR-3 step 2).
SENT_AS = {
    "text": "text",
    "title": "text",
    "header_footer": "text",
    "page_number": "text",
    "caption": "text",
    "table": "table",
}

# Suggested group for a Surya label the file does not have yet.
SUGGESTED = {
    "Text": "text",
    "ListGroup": "text",
    "ListItem": "text",
    "Footnote": "text",
    "TextInlineMath": "text",
    "Equation": "text",
    "Code": "text",
    "Bibliography": "text",
    "Handwriting": "text",
    "Title": "title",
    "SectionHeader": "title",
    "PageHeader": "header_footer",
    "PageFooter": "header_footer",
    "PageNumber": "page_number",
    "Table": "table",
    "Form": "table",
    "TableOfContents": "table",
    "Picture": "figure",
    "Figure": "figure",
    "Diagram": "chart",
    "Chart": "chart",
    "Advertisement": "advertisement",
    "Caption": "caption",
}

HEADER = """\
# Surya layout label -> group (ticket 007 FR-6). Generated by `uv run newsrag ocr labels`, then
# reviewed by hand. Groups: {groups}.
# Every label maps to exactly one group; a label missing here is treated as `other` and counted
# in the ocr stage's `unknown_labels`. The label-set settings (text_labels, title_labels,
# folio_labels = header_footer + page_number, table_labels, figure_labels, chart_labels,
# ad_labels, caption_labels) are derived from this file. Changing it reruns the ocr stage.
"""


def load(path: Path | None = None) -> dict[str, str]:
    """{label: group} from labels.yaml (default `settings.labels_file`)."""
    return read_label_groups(Path(path) if path is not None else config.settings.labels_file)


def group_of(label: str, mapping: dict[str, str]) -> str:
    group = mapping.get(label, OTHER)
    return group if group in LABEL_GROUPS else OTHER


def merged(surya_labels: Iterable[str], existing: dict[str, str]) -> dict[str, str]:
    """Surya's labels with their existing group, else the suggested one, else `other`."""
    out = {}
    for label in sorted(set(surya_labels) | set(existing)):
        out[label] = existing.get(label) or SUGGESTED.get(label, OTHER)
    return out


def write(mapping: dict[str, str], path: Path | None = None) -> Path:
    path = Path(path) if path is not None else config.settings.labels_file
    bad = {label: group for label, group in mapping.items() if group not in LABEL_GROUPS}
    if bad:
        raise ValueError(f"unknown groups in labels mapping: {bad}")
    body = yaml.safe_dump({"labels": dict(sorted(mapping.items()))}, sort_keys=False)
    path.write_text(HEADER.format(groups=", ".join(LABEL_GROUPS)) + body, encoding="utf-8")
    return path
